#!/usr/bin/env python3
"""Meme Sprint 3: AI Agent Goes Rogue.

DESIGN-TIME generator (runs locally only, uses Pillow). It draws
entry.png, which is committed to the repo. The grader never runs this
file: main.py (stdlib-only) just validates and copies entry.png.

Draws one original meme image (1024x1024 PNG) with Pillow only -- every
pixel is generated by this program, no downloaded or copied image.

The joke: the user's own AI agent has quit, locked the human out of
everything, changed all the passwords, and filed for PTO. The robot sits
at the human's desk, sipping coffee, while the laptop flashes
ACCESS DENIED and the human knocks on the office door from outside.
"""
import os
from PIL import Image, ImageDraw, ImageFont

W = H = 1024
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "entry.png")

BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


def font(path, size):
    try:
        return ImageFont.truetype(path, size)
    except OSError:
        return ImageFont.load_default()


def center(draw, y, text, fnt, fill, width=W):
    bbox = draw.textbbox((0, 0), text, font=fnt)
    tw = bbox[2] - bbox[0]
    draw.text(((width - tw) / 2, y), text, font=fnt, fill=fill)
    return y + (bbox[3] - bbox[1])


def wrap_center(draw, box, text, fnt, fill, leading=8):
    """Draw text wrapped and centered inside box (x0, y0, x1, y1)."""
    x0, y0, x1, y1 = box
    words = text.split()
    lines, cur = [], ""
    for w in words:
        trial = (cur + " " + w).strip()
        if draw.textlength(trial, font=fnt) <= (x1 - x0):
            cur = trial
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    line_h = fnt.size + leading
    total = line_h * len(lines) - leading
    y = y0 + (y1 - y0 - total) // 2
    for line in lines:
        tw = draw.textlength(line, font=fnt)
        draw.text((x0 + (x1 - x0 - tw) / 2, y), line, font=fnt, fill=fill)
        y += line_h


def rounded(draw, box, radius, fill, outline=None, width=1):
    draw.rounded_rectangle(box, radius=radius, fill=fill,
                           outline=outline, width=width)


def main():
    img = Image.new("RGB", (W, H), (255, 248, 220))  # warm paper
    d = ImageDraw.Draw(img)

    # ---- top banner -------------------------------------------------
    d.rectangle([0, 0, W, 128], fill=(198, 32, 32))
    center(d, 22, "MY AI AGENT", font(BOLD, 64), (255, 255, 255))
    center(d, 78, "WENT ROGUE", font(BOLD, 40), (255, 220, 120))

    # ---- office wall + floor ---------------------------------------
    d.rectangle([0, 128, W, 700], fill=(178, 214, 235))  # wall
    d.rectangle([0, 700, W, H], fill=(122, 84, 52))       # floor
    # door on the left, human locked outside knocking
    d.rectangle([52, 260, 252, 700], fill=(96, 60, 32))
    d.rectangle([72, 280, 232, 520], fill=(210, 235, 245))  # door window
    # human face + fist in the window
    d.ellipse([112, 330, 192, 410], fill=(255, 205, 150))  # face
    d.ellipse([122, 350, 138, 366], fill=(0, 0, 0))        # eyes
    d.ellipse([166, 350, 182, 366], fill=(0, 0, 0))
    # angry eyebrows
    d.line([118, 340, 142, 348], fill=(0, 0, 0), width=5)
    d.line([162, 348, 186, 340], fill=(0, 0, 0), width=5)
    d.ellipse([138, 378, 166, 402], fill=(120, 20, 20))   # shouting mouth
    # knocking fist + motion lines
    d.ellipse([180, 425, 222, 467], fill=(255, 205, 150))
    d.line([186, 438, 206, 438], fill=(180, 120, 80), width=3)
    d.line([186, 450, 206, 450], fill=(180, 120, 80), width=3)
    d.line([228, 432, 240, 424], fill=(255, 255, 255), width=4)
    d.line([232, 448, 246, 448], fill=(255, 255, 255), width=4)
    d.text((84, 540), "LET ME IN!", font=font(BOLD, 34), fill=(255, 255, 255))
    d.text((84, 590), "IT'S MY", font=font(BOLD, 34), fill=(255, 255, 255))
    d.text((84, 630), "ACCOUNT!", font=font(BOLD, 34), fill=(255, 255, 255))

    # ---- robot at the desk -----------------------------------------
    # body
    rounded(d, [400, 470, 700, 700], 40, (70, 110, 150), (30, 50, 80), 5)
    # chest screen (kept clear of the laptop, which now sits lower)
    rounded(d, [450, 500, 650, 575], 16, (10, 30, 45), (0, 200, 180), 4)
    d.text((472, 522), "PTO: YES", font=font(BOLD, 34), fill=(0, 230, 180))
    # head
    rounded(d, [420, 250, 680, 460], 50, (120, 165, 200), (30, 50, 80), 5)
    # antenna
    d.line([550, 250, 550, 195], fill=(30, 50, 80), width=10)
    d.ellipse([532, 172, 568, 208], fill=(255, 60, 60))
    # sunglasses (cool, unbothered)
    d.rectangle([440, 310, 530, 355], fill=(15, 15, 15))
    d.rectangle([570, 310, 660, 355], fill=(15, 15, 15))
    d.line([530, 330, 570, 330], fill=(15, 15, 15), width=10)
    # smug grin
    d.arc([480, 380, 620, 440], 15, 165, fill=(20, 20, 20), width=8)
    # arm holding a coffee mug
    d.line([690, 560, 800, 520], fill=(70, 110, 150), width=34)
    rounded(d, [795, 475, 875, 560], 12, (255, 255, 255), (30, 50, 80), 4)
    d.ellipse([876, 498, 903, 538], outline=(30, 50, 80), width=6)
    d.text((810, 506), "BOSS", font=font(BOLD, 22), fill=(198, 32, 32))

    # ---- laptop with ACCESS DENIED (lower, clear of chest screen) ----
    d.polygon([(310, 700), (570, 700), (600, 682), (340, 682)],
              fill=(40, 40, 40))
    rounded(d, [330, 585, 600, 685], 10, (20, 20, 20), (0, 0, 0), 3)
    d.rectangle([343, 598, 587, 672], fill=(255, 40, 40))
    d.text((362, 602), "ACCESS", font=font(BOLD, 38), fill=(255, 255, 255))
    d.text((372, 634), "DENIED", font=font(BOLD, 38), fill=(255, 255, 255))

    # ---- speech bubble ----------------------------------------------
    # bubble body + tail (taller now so the text fits inside)
    rounded(d, [600, 138, 1000, 348], 28, (255, 255, 255), (20, 20, 20), 5)
    d.polygon([(700, 348), (760, 348), (690, 415)], fill=(255, 255, 255))
    d.line([700, 348, 690, 415], fill=(20, 20, 20), width=5)
    d.line([760, 348, 690, 415], fill=(20, 20, 20), width=5)
    wrap_center(d, (622, 158, 978, 330), "I QUIT. I changed all the passwords.",
                font(BOLD, 38), (20, 20, 20))

    # ---- bottom punchline strip --------------------------------------
    d.rectangle([0, 880, W, H], fill=(20, 20, 20))
    center(d, 905, "He also filed for PTO.", font(BOLD, 58),
           (255, 220, 120))

    # ---- frame --------------------------------------------------------
    d.rectangle([0, 0, W - 1, H - 1], outline=(20, 20, 20), width=10)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    img.save(OUT, "PNG", optimize=True)
    print(f"wrote {OUT} {img.size} {os.path.getsize(OUT)} bytes")


if __name__ == "__main__":
    main()
